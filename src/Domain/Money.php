<?php

declare(strict_types=1);

namespace App\Domain;

/**
 * Перевод между единицами контракта и внутренним представлением.
 *
 * Внутри системы деньги всегда хранятся и сравниваются в минорных единицах
 * целым числом: копейки, центы. Мажорные единицы существуют только
 * на границах — во входящем контракте, в ответе API и в отчётах.
 *
 * Так устроены Stripe (amount: 100 — это $1.00) и Steam Web API
 * (price_overview.final: 5999 — это $59.99).
 *
 * Контракт платёжной системы в этом проекте оперирует целыми рублями,
 * поэтому преобразование выполняется в трёх местах: загрузка каталога,
 * приём вебхука, формирование ответа.
 */
final class Money
{
    private const MINOR_UNITS = 100;

    /** Из единиц контракта во внутреннее представление. */
    public static function toMinor(int $amount): int
    {
        return $amount * self::MINOR_UNITS;
    }

    /**
     * Из внутреннего представления в единицы контракта.
     *
     * Контракт не предусматривает дробных сумм, поэтому остаток от деления
     * означал бы рассогласование данных и подлежит разбору через сверку,
     * а не молчаливому округлению.
     */
    public static function toContract(int $minor): int
    {
        return intdiv($minor, self::MINOR_UNITS);
    }
}
